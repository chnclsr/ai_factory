#!/usr/bin/env node
// Regenerates the browser extension's model list from router_config.json so the picker
// always offers exactly the engines and models the router accepts.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, CONFIG_FILE } from '../lib/paths.mjs';

const EFFORT_LEVELS = ['low', 'medium', 'high', 'xhigh', 'max'];
const config = JSON.parse(fs.readFileSync(CONFIG_FILE, 'utf8'));

// The picker offers the engines the router actually uses: those in the fallback chain, plus
// Claude, which is the critic. Engines kept in the config for manual --engine calls (OpenCode,
// Codex) stay out of the picker.
const offered = new Set([...config.fallback_chain.map(step => step.engine), 'claude']);
const engines = {};
for (const [engine, definition] of Object.entries(config.engines)) {
  if (!offered.has(engine)) continue;
  engines[engine] = {
    default: definition.default_model,
    // Claude is the only engine whose CLI takes a reasoning-effort flag.
    effort: engine === 'claude' ? EFFORT_LEVELS : [],
    models: Object.keys(definition.models)
  };
}

const data = {
  engines,
  chain: config.fallback_chain.map(step => `${step.engine}/${step.model}`)
};

const target = path.join(ROOT, 'browser-extension', 'models.js');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target,
  '// Generated by scripts/build-extension.mjs from router_config.json. Do not edit by hand.\n' +
  'var AI_FACTORY_MODELS = ' + JSON.stringify(data, null, 2) + ';\n', 'utf8');

console.log('Wrote ' + target);
for (const [engine, value] of Object.entries(engines)) {
  console.log(`  ${engine}: ${value.models.length} models, default ${value.default}`);
}
